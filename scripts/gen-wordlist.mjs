// Embed the EFF long word list in a module, byte-for-byte.
//
// This SDK runs where there is no filesystem (browsers, Workers, Deno without --allow-read), so
// the list cannot be read at runtime the way Python and Go read theirs. The module carries the
// file's exact text instead, and test/generate.test.ts asserts that the embedded text has the
// EFF's digest and equals src/eff_large_wordlist.txt. Rerun this after changing that file, which
// should never happen.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const source = fileURLToPath(new URL('../src/eff_large_wordlist.txt', import.meta.url))
const target = fileURLToPath(new URL('../src/eff-wordlist.ts', import.meta.url))

const text = readFileSync(source, 'utf8')
writeFileSync(
  target,
  '// Generated by scripts/gen-wordlist.mjs from src/eff_large_wordlist.txt. Do not edit.\n' +
    '//\n' +
    '// The EFF long word list, byte-for-byte as the EFF publishes it (dice numbers, a tab, the\n' +
    '// word). By the Electronic Frontier Foundation, licensed under CC BY 3.0 US; see NOTICE.\n' +
    // Annotated, so the declaration file says `string` rather than carrying the list again as a
    // literal type.
    `export const EFF_LARGE_WORDLIST_TEXT: string = ${JSON.stringify(text)}\n`,
)
console.error(`wrote ${target} (${text.length} characters)`)
